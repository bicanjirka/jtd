package td.tower.upgrade;

/**
 * One of a tower's four upgrade slots: {@code CORE} for the chain that opens the others, {@code BASE}
 * for chassis stats, {@code HEAD} for weapon stats, {@code SPECIAL} for an augment. Declaration order
 * is display order.
 */
public enum UpgradeSlot {
    CORE, BASE, HEAD, SPECIAL
}
